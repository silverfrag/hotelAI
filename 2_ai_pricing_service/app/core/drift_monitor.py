"""Statistical Drift Monitoring (PSI, Kolmogorov-Smirnov, Wasserstein-1) for Hotel AI pricing.

Supports both:
1. Empirical reference distributions loaded from `random_forest_v2.conformal.json`
   (36,090 Portugal City Hotel training rows; zero synthetic sampling on V2 features).
2. Deterministic parametric fallback (`DEFAULT_BASELINE_STATS`) for operational features
   without a Portugal training column (e.g. `occupancy_ratio`) or legacy unit tests.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import UTC, datetime
from functools import lru_cache
import json
from pathlib import Path
from typing import Any, Final, Literal

import numpy as np
from scipy.stats import ks_2samp, wasserstein_distance

PSI_STABLE_THRESHOLD: Final = 0.10
PSI_ALERT_THRESHOLD: Final = 0.25
EPSILON: Final = 1e-4

DriftStatus = Literal["stable", "warning", "drift_detected"]
OverallDriftStatus = Literal["healthy", "degraded", "drift_alert"]
BaselineSource = Literal[
    "portugal_v2_training_empirical",
    "synthetic_operational_prior",
    "synthetic_fallback",
]

DEFAULT_REFERENCE_PATH: Final[Path] = (
    Path(__file__).resolve().parents[1] / "models" / "random_forest_v2.conformal.json"
)


@dataclass(frozen=True, slots=True)
class FeatureDriftReport:
    feature: str
    psi: float
    status: DriftStatus
    baseline_mean: float
    current_mean: float
    baseline_std: float
    current_std: float
    ks_stat: float = 0.0
    ks_pvalue: float = 1.0
    wasserstein_distance: float = 0.0
    baseline_median: float = 0.0
    current_median: float = 0.0
    baseline_rows: int = 0
    baseline_source: BaselineSource = "synthetic_fallback"


@dataclass(frozen=True, slots=True)
class DriftAssessment:
    assessed_at: str
    overall_status: OverallDriftStatus
    total_features_monitored: int
    features_with_drift: int
    features_with_warning: int
    reports: list[FeatureDriftReport]
    recommendations: list[str]
    baseline_source: str = "synthetic_fallback"


def calculate_psi(
    baseline: np.ndarray,
    current: np.ndarray,
    num_bins: int = 10,
) -> float:
    """Calculate the Population Stability Index between baseline and current distributions."""
    if len(baseline) == 0 or len(current) == 0:
        return 0.0

    quantiles = np.linspace(0, 100, num_bins + 1)
    bin_edges = np.percentile(baseline, quantiles)
    bin_edges = np.unique(bin_edges)

    if len(bin_edges) < 2:
        return 0.0

    bin_edges[0] = -np.inf
    bin_edges[-1] = np.inf

    baseline_counts, _ = np.histogram(baseline, bins=bin_edges)
    current_counts, _ = np.histogram(current, bins=bin_edges)

    baseline_pct = np.maximum(baseline_counts / len(baseline), EPSILON)
    current_pct = np.maximum(current_counts / len(current), EPSILON)

    baseline_pct /= np.sum(baseline_pct)
    current_pct /= np.sum(current_pct)

    psi = np.sum((current_pct - baseline_pct) * np.log(current_pct / baseline_pct))
    return float(max(0.0, psi))


def classify_psi(psi: float) -> DriftStatus:
    if psi < PSI_STABLE_THRESHOLD:
        return "stable"
    if psi < PSI_ALERT_THRESHOLD:
        return "warning"
    return "drift_detected"


@lru_cache(maxsize=4)
def load_empirical_drift_reference(
    reference_path: str | None = None,
) -> dict[str, dict[str, Any]]:
    """Load real empirical training distributions generated by build_v2_conformal_reference.py."""
    path = Path(reference_path) if reference_path else DEFAULT_REFERENCE_PATH
    if not path.exists():
        return {}
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
        ref = payload.get("drift_reference", {})
        return ref if isinstance(ref, dict) else {}
    except Exception:
        return {}


# Fallback stats for non-V2 operational signals (never existed in Portugal historical CSV)
DEFAULT_BASELINE_STATS: Final[dict[str, dict[str, float]]] = {
    "lead_time": {"mean": 18.5, "std": 14.2, "min": 0.0, "max": 120.0},
    "stay_nights": {"mean": 2.4, "std": 1.6, "min": 1.0, "max": 14.0},
    "weekend_share": {"mean": 0.38, "std": 0.35, "min": 0.0, "max": 1.0},
    "guest_count": {"mean": 2.1, "std": 1.1, "min": 1.0, "max": 6.0},
    "occupancy_ratio": {"mean": 0.62, "std": 0.22, "min": 0.0, "max": 1.0},
    "booking_velocity_score": {"mean": 0.50, "std": 0.18, "min": 0.0, "max": 1.0},
}
DISCRETE_INTEGER_FEATURES: Final[frozenset[str]] = frozenset({
    "lead_time",
    "stay_nights",
    "weekend_nights",
    "guest_count",
})


def _resolve_baseline_distribution(
    *,
    feature_name: str,
    current_arr: np.ndarray,
    use_empirical_reference: bool,
    empirical_refs: dict[str, dict[str, Any]],
) -> tuple[np.ndarray, float, float, float, int, BaselineSource]:
    if use_empirical_reference and feature_name in empirical_refs:
        entry = empirical_refs[feature_name]
        quantiles = entry.get("ecdf_quantiles")
        if isinstance(quantiles, list) and len(quantiles) >= 10:
            ref_arr = np.asarray(quantiles, dtype=float)
            return (
                ref_arr,
                float(entry.get("mean", np.mean(ref_arr))),
                float(entry.get("std", np.std(ref_arr))),
                float(entry.get("median", np.median(ref_arr))),
                int(entry.get("sample_rows", len(ref_arr))),
                "portugal_v2_training_empirical",
            )

    stats = DEFAULT_BASELINE_STATS.get(
        feature_name,
        {
            "mean": float(np.mean(current_arr)),
            "std": float(np.std(current_arr)) or 1.0,
            "min": 0.0,
            "max": 1.0,
        },
    )
    rng = np.random.default_rng(42)
    ref_sample = rng.normal(
        loc=stats["mean"],
        scale=max(0.1, stats["std"]),
        size=max(500, len(current_arr) * 2),
    )
    if feature_name in DISCRETE_INTEGER_FEATURES:
        ref_sample = np.round(ref_sample)
    if "min" in stats and "max" in stats:
        ref_sample = np.clip(ref_sample, stats["min"], stats["max"])

    source: BaselineSource = (
        "synthetic_operational_prior"
        if use_empirical_reference
        else "synthetic_fallback"
    )
    return (
        ref_sample,
        float(stats["mean"]),
        float(stats["std"]),
        float(np.median(ref_sample)),
        int(len(ref_sample)),
        source,
    )


def assess_feature_drift(
    feature_observations: dict[str, list[float]],
    *,
    use_empirical_reference: bool = False,
    reference_path: str | None = None,
) -> DriftAssessment:
    """Assess drift across observed features using PSI, 2-sample KS test, and Wasserstein-1."""
    reports: list[FeatureDriftReport] = []
    recommendations: list[str] = []
    drift_count = 0
    warning_count = 0
    observed_sources: set[str] = set()

    empirical_refs = (
        load_empirical_drift_reference(reference_path)
        if use_empirical_reference
        else {}
    )

    for feature_name, current_values in feature_observations.items():
        if not current_values:
            continue

        current_arr = np.asarray(current_values, dtype=float)
        (
            ref_sample,
            baseline_mean,
            baseline_std,
            baseline_median,
            baseline_rows,
            feature_source,
        ) = _resolve_baseline_distribution(
            feature_name=feature_name,
            current_arr=current_arr,
            use_empirical_reference=use_empirical_reference,
            empirical_refs=empirical_refs,
        )
        observed_sources.add(feature_source)

        psi = round(calculate_psi(ref_sample, current_arr), 4)
        status = classify_psi(psi)

        ks_res = ks_2samp(ref_sample, current_arr)
        ks_stat = round(float(ks_res.statistic), 4)
        ks_pval = round(float(ks_res.pvalue), 6)
        wass = round(float(wasserstein_distance(ref_sample, current_arr)), 4)

        if status == "drift_detected":
            drift_count += 1
            recommendations.append(
                f"Phát hiện dịch chuyển phân phối trên '{feature_name}' "
                f"(PSI = {psi:.3f}, KS = {ks_stat:.3f}, W1 = {wass:.2f}, p = {ks_pval:.4g}). "
                "Phản ánh khác biệt ngữ cảnh đặt phòng White Sand Đà Nẵng so với baseline."
            )
        elif status == "warning":
            warning_count += 1
            recommendations.append(
                f"Cảnh báo dịch chuyển nhẹ trên '{feature_name}' "
                f"(PSI = {psi:.3f}, KS = {ks_stat:.3f}, W1 = {wass:.2f}). "
                "Nên theo dõi thêm trong chu kỳ 7 ngày tới."
            )

        reports.append(
            FeatureDriftReport(
                feature=feature_name,
                psi=psi,
                status=status,
                baseline_mean=round(baseline_mean, 3),
                current_mean=round(float(np.mean(current_arr)), 3),
                baseline_std=round(baseline_std, 3),
                current_std=round(float(np.std(current_arr)), 3),
                ks_stat=ks_stat,
                ks_pvalue=ks_pval,
                wasserstein_distance=wass,
                baseline_median=round(baseline_median, 3),
                current_median=round(float(np.median(current_arr)), 3),
                baseline_rows=baseline_rows,
                baseline_source=feature_source,
            )
        )

    if drift_count > 0:
        overall: OverallDriftStatus = "drift_alert"
    elif warning_count > 0:
        overall = "degraded"
    else:
        overall = "healthy"
        recommendations.append(
            "Tất cả các đặc trưng đều ổn định so với phân phối tham chiếu (PSI < 0.10)."
        )

    if observed_sources == {"portugal_v2_training_empirical"}:
        agg_source = "portugal_v2_training_empirical"
    elif "portugal_v2_training_empirical" in observed_sources:
        agg_source = "mixed_empirical_and_prior"
    elif "synthetic_operational_prior" in observed_sources:
        agg_source = "synthetic_operational_prior"
    else:
        agg_source = "synthetic_fallback"

    return DriftAssessment(
        assessed_at=datetime.now(UTC).isoformat(),
        overall_status=overall,
        total_features_monitored=len(reports),
        features_with_drift=drift_count,
        features_with_warning=warning_count,
        reports=reports,
        recommendations=recommendations,
        baseline_source=agg_source,
    )
