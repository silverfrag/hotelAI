-- Preserve the room labels shown on historical bookings even when an admin
-- later renames a room or room type.
ALTER TABLE booking_details ADD COLUMN IF NOT EXISTS room_number_snapshot VARCHAR(10);
ALTER TABLE booking_details ADD COLUMN IF NOT EXISTS room_type_name_snapshot VARCHAR(50);

UPDATE booking_details AS detail
SET room_number_snapshot = room.room_number,
    room_type_name_snapshot = room_type.name
FROM rooms AS room
INNER JOIN room_types AS room_type ON room_type.type_id = room.type_id
WHERE detail.room_id = room.room_id
  AND (detail.room_number_snapshot IS NULL OR detail.room_type_name_snapshot IS NULL);

ALTER TABLE booking_details ALTER COLUMN room_number_snapshot SET NOT NULL;
ALTER TABLE booking_details ALTER COLUMN room_type_name_snapshot SET NOT NULL;

